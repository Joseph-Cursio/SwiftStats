import Foundation
import SwiftParser
@testable import SwiftStatsCore
import Testing

/// Which files count as generated (PRD D8).
@Suite("Generated code")
struct GeneratedCodeTests {
    private static let defaults = GeneratedCode.defaultGlobs.map(GlobPattern.init)

    private static func file(_ path: String, _ source: String) -> ParsedFile {
        ParsedFile(
            path: path,
            source: source,
            tree: Parser.parse(source: source),
            hasByteOrderMark: false,
            sha256: ContentHash.sha256(Data(source.utf8))
        )
    }

    @Test("the default globs match generated paths and nothing else")
    func defaultGlobs() {
        let generated = [
            "Tests/LibTests/PropertyLawTests.generated.swift", "Sources/Lib/Model.pb.swift",
            "Sources/Lib/Service.grpc.swift", "Tests/LibTests/Generated/SwiftInfer/Stub.swift"
        ]
        for path in generated {
            #expect(GeneratedCode.isGenerated(Self.file(path, "struct S { }\n"), globs: Self.defaults), "\(path)")
        }
        let handWritten = Self.file("Sources/Lib/Generator.swift", "struct Generator { }\n")
        #expect(GeneratedCode.isGenerated(handWritten, globs: Self.defaults) == false)
    }

    @Test("a known header in the leading comment marks a file, whatever the globs")
    func headers() {
        let sources = [
            "// Auto-generated by `swift-infer discover --interactive`\nimport Testing\n",
            "// GENERATED by PropertyLawDiscoveryPlugin\nimport PropertyLawKit\n",
            "// swiftlint:disable all\n// Generated using SwiftGen\nenum L10n { }\n",
            "// Generated using Sourcery 2.2.5\nstruct Mock { }\n",
            "/* DO NOT EDIT.\n   Produced by protoc. */\nstruct Message { }\n",
            "// DO NOT EDIT\n"
        ]
        for source in sources {
            #expect(GeneratedCode.isGenerated(Self.file("Sources/Lib/A.swift", source), globs: []), "\(source)")
        }
    }

    @Test("header text after the first token, or in a doc comment on a later declaration, doesn't count")
    func headerOnlyLeading() {
        let late = "import Foundation\n// DO NOT EDIT the next line by hand\nlet value = 1\n"
        #expect(GeneratedCode.isGenerated(Self.file("Sources/Lib/A.swift", late), globs: []) == false)
    }

    @Test("`generated:` replaces the default globs; an empty list leaves only headers")
    func configuration() throws {
        let custom = try SwiftStatsConfiguration.parse("generated:\n  - Sources/Lib/Mocks\n", path: "c.yml")
        let empty = try SwiftStatsConfiguration.parse("generated:\n", path: "c.yml")
        let none = try SwiftStatsConfiguration.parse("excluded: []\n", path: "c.yml")

        #expect(custom.generated == ["Sources/Lib/Mocks"])
        #expect(empty.generated.isEmpty)
        #expect(none.generated == GeneratedCode.defaultGlobs)
        #expect(custom.unusedKeys.isEmpty)
        #expect(throws: ScanError.self) {
            try SwiftStatsConfiguration.parse("generated: Sources\n", path: "c.yml")
        }
    }
}
