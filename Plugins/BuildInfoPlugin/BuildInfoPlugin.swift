//
//  BuildInfoPlugin.swift
//  BuildInfoPlugin
//
//  Embeds SwiftStats' build identity (PRD §6.2) in the SwiftStatsBuildInfo
//  target: a hash of the build inputs (`Sources/`, `Package.swift`,
//  `Package.resolved`, `Plugins/`) at HEAD plus their uncommitted changes,
//  and the commit and dirty flag as a label. It runs before every build and
//  uses read-only git only, since the plugin sandbox allows writes to
//  temporary directories and the plugin's own. Without git, or when git's
//  top level isn't this package (a copy inside another repository), it
//  writes empty values and the executable falls back to its own hash.
//

import Foundation
import PackagePlugin

/// Writes `BuildInfo.swift` into the target's generated sources.
@main
struct BuildInfoPlugin: BuildToolPlugin {
    /// The shell script that writes the file; `$1` is the package directory
    /// and `$2` the file to write. It always writes the file, so a missing
    /// git never fails the build, and replaces it only when the content
    /// changes, so an unchanged build recompiles nothing.
    private static let script = #"""
    package="$1"; output="$2"; git=/usr/bin/git
    commit=""; dirty=false; hash=""
    cd "$package" 2>/dev/null || exit 1
    top=$("$git" rev-parse --show-toplevel 2>/dev/null)
    if [ -n "$top" ] && [ "$(cd "$top" && pwd -P)" = "$(pwd -P)" ]; then
        commit=$("$git" rev-parse --verify --quiet HEAD 2>/dev/null)
        inputs=(Sources Package.swift Package.resolved Plugins)
        status=$("$git" --no-optional-locks status --porcelain --untracked-files=all -- "${inputs[@]}" 2>/dev/null)
        if [ -n "$status" ]; then
            dirty=true
        fi
        # Content only: the input trees at HEAD, a diff whose form no user
        # setting changes, and each untracked input's blob hash. Piped
        # straight to shasum, so no byte (a NUL included) is lost.
        hash=$(
            {
                for input in "${inputs[@]}"; do
                    echo "$input $("$git" rev-parse --verify --quiet "HEAD:$input" 2>/dev/null)"
                done
                "$git" --no-optional-locks -c core.quotepath=off diff HEAD --binary --no-ext-diff \
                    --no-textconv --no-color --no-renames --full-index --src-prefix=a/ --dst-prefix=b/ \
                    -- "${inputs[@]}" 2>/dev/null
                "$git" ls-files -z -o --exclude-standard -- "${inputs[@]}" 2>/dev/null |
                    while IFS= read -r -d '' file; do
                        printf '%s\0' "$file"
                        "$git" hash-object --no-filters -- "$file"
                    done
            } | /usr/bin/shasum -a 256 | /usr/bin/cut -d ' ' -f 1
        )
    fi
    temporary="$output.tmp"
    {
        echo "// Generated by BuildInfoPlugin; do not edit."
        echo "let generatedInputHash = \"$hash\""
        echo "let generatedCommit = \"$commit\""
        echo "let generatedDirty = $dirty"
    } > "$temporary"
    if cmp -s "$temporary" "$output"; then rm -f "$temporary"; else mv "$temporary" "$output"; fi
    """#

    /// The prebuild command that writes `BuildInfo.swift`.
    func createBuildCommands(context: PluginContext, target _: any Target) throws -> [Command] {
        let output = context.pluginWorkDirectoryURL.appending(path: "Generated")
        try FileManager.default.createDirectory(at: output, withIntermediateDirectories: true)
        return [
            .prebuildCommand(
                displayName: "Embed SwiftStats' build identity",
                executable: URL(filePath: "/bin/bash"),
                arguments: [
                    "-c",
                    Self.script,
                    "build-info",
                    context.package.directoryURL.path(percentEncoded: false),
                    output.appending(path: "BuildInfo.swift").path(percentEncoded: false)
                ],
                outputFilesDirectory: output
            )
        ]
    }
}
